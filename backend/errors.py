def get_error(key, lang="tr"):
    if lang in ALL_ERRORS:
        return ALL_ERRORS[lang].get(key, ALL_ERRORS["en"].get(key, key))
    return ERROR_EN.get(key, key) if lang == "en" else ERROR_TR.get(key, key)


def get_error_with_params(key, lang="tr", **kwargs):
    msg = get_error(key, lang)
    if kwargs:
        try:
            return msg.format(**kwargs)
        except:
            return msg
    return msg